  <h2>Making protein design more accessible</h2>
  <p>Based in the University of Edinburgh, our research focuses on improving the accessibility and reliability of protein design, with the aim of increasing its use as a tool for tackling challenges in biotechnology and synthetic biology. To do this, we're developing software that applies machine-learning, computational modelling and structural bioinformatics to help guide users through the protein-design process.</p>
  <h2>Rigorously tested methods</h2>
  <p>We apply all the methods that we create at scale in the laboratory, using the robotics available at Edinburgh through the incredible <a href="https://www.genomefoundry.org/" target="_blank" rel="noreferrer">Genome Foundry</a>. All data and scripts are made publicly available so that users are confident in the effectiveness of the methods and can apply them to their fullest.</p>
  <h2>Committed to open-access research</h2>
  <p>Our research is publicly funded, so we are committed to making our outputs publicly available, including data, software and publications.</p>
